/**
 * Rebuilds src/shared/gggCatalogue.ts from the edGGG catalogue of green gas giants
 * (https://ed-ggg.github.io/edggg/, maintained by CMDR Arcanic): body name, class, surface temperature
 * and galactic position of every catalogued GGG. Facts only — no text, no images.
 *
 *   node scripts/build-ggg-catalogue.mjs
 *
 * One request for the map list (names, positions, page numbers), then one per planet page for the class
 * and the temperature, 250 ms apart. Run it before a release when edGGG has added new ones.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const UA = { "User-Agent": "EDEXO-Compare catalogue build (github.com/bahuckel/EDEXO-Compare)" };
const LIST = "https://raw.githubusercontent.com/ed-ggg/edggg/refs/heads/master/resources/gggjson.json";
const PAGE = (n) => `https://ed-ggg.github.io/edggg/planets/ggg${n}/`;

/** edGGG's class names → the journal's `PlanetClass`. */
const CLASS = {
  "Class I": "Sudarsky class I gas giant",
  "Class II": "Sudarsky class II gas giant",
  "Class III": "Sudarsky class III gas giant",
  "Class IV": "Sudarsky class IV gas giant",
  "Class V": "Sudarsky class V gas giant",
  "Water Giant": "Water giant",
  "Water-Based Life": "Gas giant with water based life",
  "Ammonia-Based Life": "Gas giant with ammonia based life",
};

const list = JSON.parse(await (await fetch(LIST, { headers: UA })).text());
const out = [];
for (const m of list.markers) {
  const [body, link] = String(m.text).split("\n");
  const n = Number(/ggg(\d+)/.exec(link ?? "")?.[1]);
  if (!Number.isFinite(n)) throw new Error(`no GGG number in ${m.text}`);
  const html = await (await fetch(PAGE(n), { headers: UA })).text();
  const lines = html
    .replace(/<[^>]*>/g, "\n")
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);
  const after = (k) => lines[lines.indexOf(k) + 1] ?? "";
  const cls = CLASS[after("Type:")];
  const t = parseFloat(after("Temperature:"));
  if (!cls || !Number.isFinite(t)) throw new Error(`GGG #${n}: type "${after("Type:")}", temperature "${after("Temperature:")}"`);
  out.push({ n, body: body.trim(), cls, t, x: m.x, y: m.y, z: m.z });
  await new Promise((r) => setTimeout(r, 250));
}
out.sort((a, b) => a.n - b.n);

const rows = out
  .map((g) => `  [${g.n}, ${JSON.stringify(g.body)}, ${JSON.stringify(g.cls)}, ${g.t}, ${g.x}, ${g.y}, ${g.z}],`)
  .join("\n");
const src = `/**
 * The edGGG catalogue of green gas giants — https://ed-ggg.github.io/edggg/, maintained by CMDR Arcanic,
 * whose research found that surface temperature decides which gas giants turn green. Credit to them.
 *
 * Generated by scripts/build-ggg-catalogue.mjs on ${new Date().toISOString().slice(0, 10)} (${out.length} GGGs). Do not edit by hand.
 * Rows: [GGG number, body name, journal PlanetClass, surface temperature K, galactic x, y, z].
 */
export type GggCatalogueRow = readonly [number, string, string, number, number, number, number];

export const GGG_CATALOGUE: readonly GggCatalogueRow[] = [
${rows}
];
`;
writeFileSync(fileURLToPath(new URL("../src/shared/gggCatalogue.ts", import.meta.url)), src);
console.log(`${out.length} GGGs written`);
